"""Leakage-safe evaluation of the existing LSTM -> Random Forest architecture.

Expanding LSTM fits produce out-of-fold forecasts for RF training rows. A final
LSTM sees training rows and uses validation only for early stopping. Neither
the LSTM nor RF sees final-test targets before scoring. Existing artifacts are
never read or overwritten by this script.
"""

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
import tensorflow as tf
from sklearn.ensemble import RandomForestRegressor
from sklearn.preprocessing import MinMaxScaler, StandardScaler

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from evaluate import FIELDS, WINDOW, percentile, score
from training.train_lstm import build_model
from training.train_random_forest import load_resource_frame


def fit_lstm(requests: np.ndarray, train_end: int, validation_end: int, epochs: int):
    tf.keras.backend.clear_session()
    tf.keras.utils.set_random_seed(42)
    scaler = MinMaxScaler().fit(requests[:train_end, None])
    scaled = scaler.transform(requests[:validation_end, None]).ravel()
    train_indices = np.arange(WINDOW, train_end)
    validation_indices = np.arange(train_end, validation_end)
    if len(validation_indices) == 0:
        raise ValueError("LSTM validation period is empty")
    x_train = np.asarray([scaled[index - WINDOW:index] for index in train_indices])[..., None]
    x_validation = np.asarray([scaled[index - WINDOW:index] for index in validation_indices])[..., None]
    model = build_model(WINDOW)
    model.fit(
        x_train, scaled[train_indices],
        validation_data=(x_validation, scaled[validation_indices]),
        epochs=epochs, batch_size=32, verbose=0,
        callbacks=[tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=5, restore_best_weights=True)],
    )
    return model, scaler


def forecast(model, scaler, requests: np.ndarray, target_indices: np.ndarray) -> np.ndarray:
    scaled = scaler.transform(requests[:, None]).ravel()
    windows = np.asarray([scaled[index - WINDOW:index] for index in target_indices])[..., None]
    return scaler.inverse_transform(model.predict(windows, verbose=0)).ravel()


def features(frame: pd.DataFrame, target_indices: np.ndarray, predicted_rate: np.ndarray) -> np.ndarray:
    origin = target_indices - 1
    return np.column_stack([
        predicted_rate,
        frame["request_rate"].to_numpy()[origin],
        frame["cpu_utilization"].to_numpy()[origin],
        frame["memory_utilization"].to_numpy()[origin],
        frame["network_throughput"].to_numpy()[origin],
        frame["response_latency"].to_numpy()[origin],
    ])


def run(dataset: Path, epochs: int) -> dict:
    frame = load_resource_frame(dataset)
    n = len(frame)
    train_end = int(n * 0.70)
    validation_end = train_end + int(n * 0.15)
    if train_end < 100 or validation_end >= n:
        raise ValueError("Dataset too small for the locked split")
    requests = frame["request_rate"].to_numpy(dtype=float)
    # The warm-up portion trains the first upstream model. Each RF training
    # forecast is generated by a model fitted strictly before that target.
    warmup = max(WINDOW + 100, int(train_end * 0.28))
    boundaries = np.linspace(warmup, train_end, 5, dtype=int)
    rf_train_indices = np.arange(warmup, train_end)
    oof_rate = np.empty(len(rf_train_indices), dtype=float)
    folds = []
    started = time.perf_counter()
    for start, end in zip(boundaries[:-1], boundaries[1:]):
        inner_train = max(WINDOW + 1, int(start * 0.85))
        model, scaler = fit_lstm(requests, inner_train, start, epochs)
        targets = np.arange(start, end)
        oof_rate[start - warmup:end - warmup] = forecast(model, scaler, requests, targets)
        folds.append({"fit_rows_end_exclusive": int(start), "predicted_target_start": int(start),
                      "predicted_target_end_exclusive": int(end)})

    model, scaler = fit_lstm(requests, train_end, validation_end, epochs)
    remaining_indices = np.arange(train_end, n)
    remaining_rate = forecast(model, scaler, requests, remaining_indices)
    rf_validation_indices = np.arange(train_end, validation_end)
    rf_test_indices = np.arange(validation_end, n)
    x_train = features(frame, rf_train_indices, oof_rate)
    x_validation = features(frame, rf_validation_indices, remaining_rate[:len(rf_validation_indices)])
    x_test = features(frame, rf_test_indices, remaining_rate[len(rf_validation_indices):])
    rf_scaler = StandardScaler().fit(x_train)
    x_train = rf_scaler.transform(x_train)
    x_validation = rf_scaler.transform(x_validation)
    x_test = rf_scaler.transform(x_test)

    result = {
        "status": "exploratory_until_data_provenance_and_independent_session_verified",
        "dataset": str(dataset), "sha256": hashlib.sha256(dataset.read_bytes()).hexdigest(),
        "versions": {"tensorflow": tf.__version__, "keras": tf.keras.__version__,
                     "sklearn": sklearn.__version__, "pandas": pd.__version__, "numpy": np.__version__},
        "epochs_limit": epochs, "window": WINDOW, "horizon_rows": 1,
        "split": {"train_end_exclusive": train_end, "validation_end_exclusive": validation_end,
                  "test_start": validation_end, "test_rows": len(rf_test_indices),
                  "rf_train_start": warmup, "rf_train_rows": len(rf_train_indices)},
        "oof_folds": folds, "targets": {},
    }
    for name, unit in FIELDS.items():
        values = frame[name].to_numpy(dtype=float)
        actual = values[rf_test_indices].tolist()
        threshold = percentile(values[:train_end].tolist(), 0.75)
        target_result = {
            "unit": unit, "high_load_threshold_from_train": threshold,
            "persistence": score(actual, values[rf_test_indices - 1].tolist(), threshold),
            "trailing_12_mean": score(actual,
                [float(np.mean(values[index - WINDOW:index])) for index in rf_test_indices], threshold),
        }
        if name == "request_rate":
            target_result["lstm"] = score(actual, remaining_rate[len(rf_validation_indices):].tolist(), threshold)
        else:
            resource = {"cpu_utilization": "cpu", "memory_utilization": "memory",
                        "network_throughput": "network"}[name]
            regressor = RandomForestRegressor(n_estimators=200, random_state=42,
                                              min_samples_leaf=2, n_jobs=-1)
            regressor.fit(x_train, values[rf_train_indices])
            target_result["validation_mae"] = score(
                values[rf_validation_indices].tolist(), regressor.predict(x_validation).tolist(), threshold)["mae"]
            target_result["lstm_rf_pipeline"] = score(
                actual, np.maximum(0, regressor.predict(x_test)).tolist(), threshold)
        result["targets"][name] = target_result
    result["elapsed_seconds"] = time.perf_counter() - started
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", type=Path, default=ROOT / "data" / "final_dataset.csv")
    parser.add_argument("--epochs", type=int, default=30)
    args = parser.parse_args()
    print(json.dumps(run(args.dataset, args.epochs), indent=2))


if __name__ == "__main__":
    main()
